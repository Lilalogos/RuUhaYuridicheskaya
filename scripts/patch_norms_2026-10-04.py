def set_field(block: str, key: str, value: str) -> str:
    value = value.replace('"', "'")
    pat = re.compile(rf'(?m)^  {re.escape(key)}: .*$')
    if pat.search(block):
        return pat.sub(f'  {key}: "{value}"', block, count=1)
    return block.rstrip("\n") + f'\n  {key}: "{value}"\n'


def append_field(block: str, key: str, extra: str) -> str:
    m = re.search(rf'(?m)^  {re.escape(key)}: "(.*)"$', block)
    if not m:
        return block
    cur = m.group(1)
    if extra.replace('"', "'") in cur:
        return block
    return block[: m.start(1)] + cur.rstrip() + " " + extra.replace('"', "'") + block[m.end(1):]


