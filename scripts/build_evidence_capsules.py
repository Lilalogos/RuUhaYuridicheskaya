def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def pdf_pages(path: Path) -> int:
    out = subprocess.run(["pdfinfo", str(path)], capture_output=True, text=True, check=True).stdout
    m = re.search(r"^Pages:\s+(\d+)", out, re.M)
    return int(m.group(1)) if m else 0


def pdf_meta(path: Path) -> dict:
    out = subprocess.run(["pdfinfo", str(path)], capture_output=True, text=True, check=True).stdout
    meta = {}
    for key in ("Title", "Creator", "Producer", "CreationDate"):
        m = re.search(rf"^{key}:\s+(.+)$", out, re.M)
        if m:
            meta[key] = m.group(1).strip()
    return meta


def pdf_page_text(path: Path, page: int) -> str:
    return subprocess.run(
        ["pdftotext", "-f", str(page), "-l", str(page), "-layout", str(path), "-"],
        capture_output=True, text=True, check=True,
    ).stdout


QUOTE_RE = re.compile(r"^\*\*стр\. (\d+)\*\* — «(.+?)»\s*(\(.*\))?\s*$", re.S)


def parse_quotes(path: Path) -> list[tuple[int, str, str]]:
    quotes: list[tuple[int, str, str]] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line.startswith("**стр."):
            continue
        m = QUOTE_RE.match(line)
        if not m:
            # цитата может содержать «» внутри — берём последнее закрывающее «»
            page = int(re.match(r"\*\*стр\. (\d+)\*\*", line).group(1))
            body = line.split("— ", 1)[1]
            note = ""
            tail = re.search(r"\s(\([^()]*\))\s*$", body)
            if tail:
                note = tail.group(1)
                body = body[: tail.start()].rstrip()
            body = body.strip()
            if body.startswith("«") and body.endswith("»"):
                body = body[1:-1]
            quotes.append((page, body, note))
            continue
        quotes.append((int(m.group(1)), m.group(2), m.group(3) or ""))
    return quotes


def first_https(text: str) -> str:
    for m in re.finditer(r"https://\S+", text):
        return m.group(0).rstrip(",;)")
    return ""


def q(value) -> str:
    """Однострочное значение для самодельного YAML-парсера базы."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(str(v) for v in value) + "]"
    s = " ".join(str(value).split()).replace('"', "'")
    return f'"{s}"'


