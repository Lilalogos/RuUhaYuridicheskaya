def write_outcomes(outcomes: list[OrderedDict]) -> None:
    lines = [HEADER.rstrip("\n")]
    for rec in outcomes:
        first = True
        for key, value in rec.items():
            prefix = "  - " if first else "    "
            first = False
            if key == "monetary_amount" and isinstance(value, dict):
                lines.append(f"{prefix}{key}:")
                for k2, v2 in value.items():
                    lines.append(f"      {k2}: {q(v2)}")
                continue
            lines.append(f"{prefix}{key}: {q(value)}")
    (KB / REF).write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_eligible_links(outcomes: list[OrderedDict]) -> None:
    """Проставляет eligible_outcome_ids материальным нормам (только пригодные записи)."""
    path = KB / "taxonomy" / "norms.yml"
    text = path.read_text(encoding="utf-8")
    by_norm: dict[str, list[str]] = {}
    for rec in outcomes:
        if not str(rec["benchmark_eligibility"]).startswith("eligible_"):
            continue
        for norm_id in rec["linked_norm_ids"]:
            by_norm.setdefault(norm_id, []).append(rec["id"])
    blocks = re.split(r"(?m)^(?=- id: )", text)
    out = []
    for block in blocks:
        m = re.match(r"- id: (\S+)", block)
        if m:
            norm_id = m.group(1)
            is_material = re.search(r"(?m)^\s*type: \"?material\"?\s*$", block) is not None
            ids = sorted(by_norm.get(norm_id, [])) if is_material else []
            block = re.sub(r"(?m)^(\s*)eligible_outcome_ids: .*$", lambda m: m.group(1) + "eligible_outcome_ids: " + ("[" + ", ".join(ids) + "]" if ids else "[]"), block)
        out.append(block)
    path.write_text("".join(out), encoding="utf-8")
    for norm_id, ids in sorted(by_norm.items()):
        print(f"eligible_outcome_ids {norm_id} <- {ids}")


